/* global VERSION, BASE, SHELL, CORE, LAZY -- written above this file by scripts/build-web.mjs */
/*
 * The web app's service worker: keeps the app's files on the phone, so it
 * opens and runs with no signal, as the Android app does.
 *
 * Three kinds of file:
 * - SHELL: the page, manifest and icons, whose names stay the same. Each
 *   version keeps its own copy (miqat-shell-<version>), fetched past the
 *   browser's HTTP cache so a new version never gets an old page.
 * - CORE: the code, fonts and Qur'an text, named by their content hash. They
 *   live in one cache across versions (miqat-assets), so an update fetches
 *   only the files that changed.
 * - LAZY: Qur'an notes and tafsir (about 18 MB), kept the first time they're
 *   read instead of on install.
 *
 * A new version installs in the background while the old one runs, and takes
 * over the next time the app opens. Caches the page keeps itself
 * (miqat-keep-*, such as online tafsir) are left alone. Requests to other
 * sites, such as recitation and dua audio, go to the network as usual.
 */
const SHELL_CACHE = `miqat-shell-${VERSION}`;
const ASSETS = 'miqat-assets';
const LAZY_FILES = new Set(LAZY);

/** Runs `task` on every item, a few at a time. */
async function inParallel(items, limit, task) {
  const queue = [...items];
  const worker = async () => {
    for (let item = queue.shift(); item !== undefined; item = queue.shift()) await task(item);
  };
  await Promise.all(Array.from({ length: limit }, worker));
}

async function fetchOk(request) {
  const response = await fetch(request);
  if (!response.ok) throw new Error(`${response.status} for ${response.url}`);
  return response;
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const shell = await caches.open(SHELL_CACHE);
      await inParallel(SHELL, 6, async (file) => {
        const url = BASE + file;
        await shell.put(url, await fetchOk(new Request(url, { cache: 'reload' })));
      });
      const assets = await caches.open(ASSETS);
      await inParallel(CORE, 6, async (file) => {
        const url = BASE + file;
        if (await assets.match(url)) return;
        // Saved by a version from before miqat-assets: take it from there.
        const old = await caches.match(url, { ignoreSearch: true });
        await assets.put(url, old ?? (await fetchOk(url)));
      });
      await self.skipWaiting();
    })(),
  );
});

// Drop older versions' pages, and assets no version uses any more, once this
// one has all it needs.
self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith('miqat-') && key !== SHELL_CACHE && key !== ASSETS && !key.startsWith('miqat-keep-')) {
          await caches.delete(key);
        }
      }
      const wanted = new Set([...CORE, ...LAZY].map((file) => new URL(BASE + file, self.location.origin).href));
      const assets = await caches.open(ASSETS);
      for (const request of await assets.keys()) {
        if (!wanted.has(request.url)) await assets.delete(request);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;

  // Every address in the app is the same page; the router picks the screen.
  const wanted = request.mode === 'navigate' ? BASE + 'index.html' : url.pathname;
  event.respondWith(
    (async () => {
      const saved =
        (await (await caches.open(SHELL_CACHE)).match(wanted, { ignoreSearch: true })) ??
        (await (await caches.open(ASSETS)).match(wanted, { ignoreSearch: true }));
      if (saved) return saved;
      const response = await fetch(request);
      // Notes and tafsir stay once read.
      if (response.ok && LAZY_FILES.has(url.pathname.slice(BASE.length))) {
        const copy = response.clone();
        event.waitUntil(caches.open(ASSETS).then((assets) => assets.put(url.pathname, copy)));
      }
      return response;
    })(),
  );
});
